from datetime import datetime
from io import BytesIO
import json
import os
import subprocess
import sys
import time
from pathlib import Path
from uuid import uuid4
import shutil

# Absolute paths (from this file's location), so it works no matter which
# folder start.sh / server.py was started from. (Relative "../python-backend"
# only worked when started from frontend/ or middleware/; from anywhere else
# the backend wasn't found and the user got "Backend failed with exit code 2".)
BACKEND_DIR = Path(__file__).resolve().parent.parent / "python-backend"
USR_DIR = BACKEND_DIR / "Cache" / "usr"


class BackendError(Exception):
    '''
    The backend ran but reported an error (exit code 1-5). str(error) is the
    backend's own explanation, meant for the user; exit_code says what kind:
    1 invalid input, 2 no SPHEREx images for that position,
    3 archive unreachable, 4 unexpected, 5 output folder already exists.
    '''

    def __init__(self, message, exit_code):
        super().__init__(message)
        self.exit_code = exit_code


def main(DEC, RA, PIXELS, interval):
    '''
    Main function to run the middleware.

    Parameters:
    DEC: Declination coordinate string for the backend to parse
    RA: Right Ascension coordinate string for the backend to parse
    PIXELS: Number of pixels to generate
    interval: Duration in milliseconds for each frame in the GIF
    '''

    uuid = sendToBackend(DEC, RA, PIXELS)  # raises BackendError if the backend failed
    try:
        Images, metadata = getImages(uuid)
        Video = convertToVideo(Images, interval)
        # Difference images (frame minus reference, see backend.py): a second GIF,
        # shown when "Show difference images" is on. None if the backend made none.
        DiffImages = getDiffImages(uuid)
        DiffVideo = convertToVideo(DiffImages, interval) if DiffImages else None
    finally:
        # Remove the uuid folder after collecting the images - also when that failed
        shutil.rmtree(USR_DIR / uuid, ignore_errors=True)
    if DiffVideo is not None:
        sendToFrontend(DiffVideo, uuid, suffix="_diff")
    video_id = sendToFrontend(Video, uuid)  # last: the frontend waits for this one
    return video_id, metadata


def sendToBackend(DEC, RA, PIXELS, BACKEND_PATH=str(BACKEND_DIR / "backend.py")):
    '''
    Creates a uuid.
    Starts the backend process with the given DEC and RA coordinates, PIXELS, and uuid.
    The backend process will generate images based on these coordinates. 

    Parameters:
    DEC: Declination coordinate string
    RA: Right Ascension coordinate string
    PIXELS: Number of pixels to generate

    Output: uuid for this submission
    Raises BackendError (with the backend's explanation) if the backend failed.
    '''
    uuid = str(uuid4())

    result = subprocess.run(
        [sys.executable, BACKEND_PATH, DEC, RA, str(PIXELS), uuid],
        stderr=subprocess.PIPE,  # the backend writes its log and error message here
        text=True,
    )
    sys.stderr.write(result.stderr)  # keep the backend's log visible in the server console

    if result.returncode != 0:
        message = _backendErrorMessage(uuid, result.stderr, result.returncode)
        # On an error the backend still hands over Cache/usr/<uuid> (with meta.json) - remove it
        shutil.rmtree(USR_DIR / uuid, ignore_errors=True)
        raise BackendError(message, result.returncode)
    return uuid


def _backendErrorMessage(uuid, stderr, returncode):
    '''
    The backend's explanation of what went wrong: meta.json["error"] if the
    backend got as far as writing its folder, else its last "error: ..." line
    on stderr (e.g. for invalid arguments, where no folder is created).
    '''
    try:
        with open(USR_DIR / uuid / "meta.json") as f:
            error = json.load(f).get("error")
        if error:
            return error
    except (OSError, ValueError):
        pass

    errors = [line.removeprefix("error: ") for line in stderr.splitlines() if line.startswith("error: ")]
    if errors:
        return errors[-1]
    return f"Backend failed with exit code {returncode}"


def getImages(uuid):
    '''
    Waits until the uuid folder exists and contains the images generated by the backend process.
    Collects the images, and deletes the uuid folder after the images have been collected.
    
    Parameters:
    uuid: the uuid of the process

    Output: list of images in jpg format
    '''
    PATH = str(USR_DIR / uuid)

    while not os.path.exists(PATH) or not os.listdir(PATH):
        time.sleep(1)

    Images = [
        f"{PATH}/{filename}"
        for filename in sorted(os.listdir(PATH))
        if filename.endswith(".jpg")
    ]
    with (USR_DIR / uuid / "meta.json").open(encoding="utf-8") as metadata_file:
        metadata = json.load(metadata_file)
    return Images, metadata


def getDiffImages(uuid):
    '''
    Collects the difference images the backend wrote into the diff/ subfolder
    of the uuid folder (call after getImages, which waits for the folder).

    Parameters:
    uuid: the uuid of the process

    Output: list of difference images in jpg format, sorted (empty if there are none)
    '''
    PATH = str(USR_DIR / uuid / "diff")
    if not os.path.isdir(PATH):
        return []
    return [f"{PATH}/{filename}" for filename in sorted(os.listdir(PATH))
            if filename.endswith(".jpg")]


def convertToVideo(Images, interval):
    """
    Converts images into a GIF, sorting by timestamps when provided.

    Parameters:
    Images: List of JPG image paths.
    Timestamps: Optional timestamps corresponding to Images in UTC format.
    interval: Duration in milliseconds for each frame in the GIF.

    Output: GIF image as bytes.
    """
    from PIL import Image

    if not Images:
        raise ValueError(
            "At least one image is required to create a GIF"
        )

    image_paths = list(Images)

    frames = []
    try:
        for i, image in enumerate(image_paths):

            if not isinstance(image, str) or not image.lower().endswith('.jpg'):
                raise ValueError(
                    f"Image at index {i} is not a valid JPG file"
                )

            with Image.open(image) as img:
                frames.append(img.convert('RGB'))

        output = BytesIO()
        frames[0].save(
            output,
            format='GIF',
            save_all=True,
            append_images=frames[1:],
            duration=interval,
            loop=0,
        )
        return output.getvalue()

    finally:
        for frame in frames:
            frame.close()



def sendToFrontend(Video, uuid, suffix=""):
    '''
    Saves the video in gif format to the video_cache folder and returns the video_id

    Parameters:
    Video: video in gif format
    uuid: uuid of the process
    suffix: appended to the file name, e.g. "_diff" -> <uuid>_diff.gif

    Output: uuid of the process, which can be used to retrieve the video from the video_cache
    '''

    video_cache_dir = Path(__file__).resolve().parent / "video_cache"
    video_cache_dir.mkdir(parents=True, exist_ok=True)

    video_path = video_cache_dir / f"{uuid}{suffix}.gif"
    with video_path.open("wb") as f:
        f.write(Video)
    return uuid # should send the video_id to the frontend, but for now we just return the uuid


def save(metadata):
    '''
    Writes the parameters to the results.csv file for storage.

    Parameters:
    metadata: dictionary containing the parameters to be saved
    '''

    RESULTS_CSV_PATH = Path(__file__).resolve().parent / "results.csv"

    if not RESULTS_CSV_PATH.exists():
        with open(RESULTS_CSV_PATH, "w") as f:
            f.write("DEC,RA,PIXELS,interval,timestamp\n")
    with open(RESULTS_CSV_PATH, "a") as f:
        f.write(f"{metadata['DEC']},{metadata['RA']},{metadata['PIXELS']},{metadata['interval']},{datetime.now().isoformat()}\n")
