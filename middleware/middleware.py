from datetime import datetime
from io import BytesIO
import os
import subprocess
import time
from uuid import uuid4


def main(DEC, RA, PIXELS, interval=500):
    '''
    Main function to test the middleware functions.
    '''

    uuid = sendToBackend(DEC, RA, PIXELS)
    Images = getImages(uuid)
    Video = convertToVideo(Images, interval=interval)
    video_id = sendToFrontend(Video, uuid)
    print(f"Video ID: {video_id}")


def sendToBackend(DEC, RA, PIXELS, BACKEND_PATH="../python-backend/backend.py"):
    '''
    Creates a uuid.
    Starts the backend process in a shell script with the given DEC and RA coordinates, PIXELS, and uuid. 
    The backend process will generate images based on these coordinates. 

    Parameters:
    DEC: Declination coordinate in degrees
    RA: Right Ascension coordinate in degrees
    PIXELS: Number of pixels to generate
    MS: Milliseconds to wait between each image in the gif

    Output: uuid for this submission
    '''
    uuid = str(uuid4())

    shell_command = f"python3 {BACKEND_PATH} {DEC} {RA} {PIXELS} {uuid}"
    subprocess.run(shell_command, shell=True, check=True)
    return uuid


def getImages(uuid):
    '''
    Waits until the uuid folder exists and contains the images generated by the backend process.
    Collects the images, and deletes the uuid folder after the images have been collected.
    
    Parameters:
    uuid: the uuid of the process

    Output: list of images in jpg format
    '''
    PATH= f"../python-backend/Cache/usr/{uuid}"

    while not os.path.exists(PATH) or not os.listdir(PATH):
        time.sleep(1)

    Images = []
    for filename in os.listdir(PATH):
        if filename.endswith(".jpg"):
            Images.append(f"{PATH}/{filename}")

    os.rmdir(PATH)  # Remove the uuid folder after collecting the images
    return Images


def convertToVideo(Images, Timestamps=None, interval=500):
    """
    Converts images into a GIF, sorting by timestamps when provided.

    Parameters:
    Images: List of JPG image paths.
    Timestamps: Optional timestamps corresponding to Images in UTC format.
    interval: Duration in milliseconds for each frame in the GIF (default: 500ms).

    Output: GIF image as bytes.
    """
    from PIL import Image

    if not Images:
        raise ValueError(
            "At least one image is required to create a GIF"
        )

    image_paths = list(Images)
    if Timestamps is not None:
        if len(image_paths) != len(Timestamps):
            raise ValueError("Images and Timestamps must have the same length")

        image_timestamps = []
        for i, (image, timestamp) in enumerate(zip(image_paths, Timestamps)):
            if not isinstance(image, str) or not image.lower().endswith('.jpg'):
                raise ValueError(f"Image at index {i} is not a valid JPG file")
            if not isinstance(timestamp, str):
                raise ValueError(f"Timestamp at index {i} is not a valid string")
            try:
                parsed_timestamp = datetime.strptime(
                    timestamp, '%Y-%m-%d %H:%M:%S'
                )
            except ValueError as exc:
                raise ValueError(
                    f"Timestamp at index {i} must use YYYY-MM-DD HH:MM:SS format"
                ) from exc
            image_timestamps.append((parsed_timestamp, image))

        image_timestamps.sort(key=lambda item: item[0])
        image_paths = [image for _, image in image_timestamps]

    frames = []
    try:
        for i, image in enumerate(image_paths):

            if not isinstance(image, str) or not image.lower().endswith('.jpg'):
                raise ValueError(
                    f"Image at index {i} is not a valid JPG file"
                )

            with Image.open(image) as img:
                frames.append(img.convert('RGB'))

        output = BytesIO()
        frames[0].save(
            output,
            format='GIF',
            save_all=True,
            append_images=frames[1:],
            duration=interval,
            loop=0,
        )
        return output.getvalue()

    finally:
        for frame in frames:
            frame.close()



def sendToFrontend(Video, uuid):
    '''
    Saves the video in gif format to the video_cache folder and returns the video_id

    Parameters:
    Video: video in gif format
    uuid: uuid of the process

    Output: uuid of the process, which can be used to retrieve the video from the video_cache
    '''

    os.makedirs("video_cache", exist_ok=True)

    video_path = os.path.join("video_cache", f"{uuid}.gif")
    with open(video_path, "wb") as f:
        f.write(Video)
    return uuid # should send the video_id to the frontend, but for now we just return the uuid

